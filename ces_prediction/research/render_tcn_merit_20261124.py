"""Expose existing audited B94 paired comparisons; no scoring/refit/bootstrap.

Consumed by docs/paper/tcn_merit_existing_20261124.md and the training plan.
"""
import hashlib
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'docs/paper/b94_methods.json'
OUT = ROOT / 'docs/paper/tcn_merit_existing_20261124.md'


def inventory():
    """Read only row indices and masks, never prediction/target values."""
    data = ROOT / 'data'
    with np.load(data / '.b75/sets.npz', allow_pickle=False) as z:
        masks75 = {k: z[k] for k in z.files if k in ('common_F', 'common_L5', 'S_F', 'S_L5')}
    with np.load(data / '.b78/sets.npz', allow_pickle=False) as z:
        masks78 = {k: z[k] for k in ('common_F', 'common_L5')}
    cells = []
    for unit in ('V1_r2_k0', 'V2_s1_k0', 'V3_q3', 'V4a'):
        for rule in ('D10', 'D50', 'D100', 'D300', 'D650', 'D1000', 'S', 'K10'):
            p = data / '.b94/predictions' / f'{unit}__1701__TX__{rule}.npz'
            with np.load(p, allow_pickle=False) as z:
                idx = z['idx']
            for target in ('F', 'L5'):
                mask = (masks78 if rule == 'K10' else masks75)[('S_' if rule == 'S' else 'common_') + target]
                support = idx[mask[idx]]
                sources = {
                    'specialized_GP_tree': data / ('.b78' if rule == 'K10' else '.b75') / 'fits' / f'{unit}__TX__{rule}__{target}.npz',
                    'mixture_GP_tree': data / '.b84/fits' / f'{unit}__TXall__{rule}.npz' if target == 'L5' else None,
                    'D10_applied_GP_tree': data / ('.b78' if rule == 'K10' else '.b75') / 'fits' / f'{unit}__TXa__{rule}__{target}.npz',
                }
                for label, src in sources.items():
                    row = {'unit': unit, 'rule': rule, 'target': target, 'reference': label,
                           'tcn_mask_rows': len(support), 'exists': src is not None and src.exists()}
                    if row['exists']:
                        with np.load(src, allow_pickle=False) as z:
                            ref_idx = z['idx']
                        shared = np.intersect1d(support, ref_idx)
                        row.update(common_index_rows=len(shared),
                                   tcn_index_rows_missing=len(support) - len(shared),
                                   reference_index_sha256=hashlib.sha256(ref_idx.tobytes()).hexdigest())
                    cells.append(row)
    result = {'metadata_only': True, 'no_est_or_target_values_read': True,
              'note': 'Index coverage is not full manifest/target/causality parity. B84 is L5 and excludes V2.',
              'cells': cells}
    p = ROOT / 'data/.tcn_merit_plan_20261124/index_inventory.json'
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(result, indent=2), encoding='utf8')
    return result


def main():
    inv = inventory()
    z = json.loads(SOURCE.read_text(encoding='utf8'))
    lines = ['# TCN merit: existing paired evidence, not a new experiment', '',
             'Source: `docs/paper/b94_methods.json`; SHA256 `' + hashlib.sha256(SOURCE.read_bytes()).hexdigest() + '`.', '',
             'Generated by `ces_prediction/research/render_tcn_merit_20261124.py`.',
             'No predictions, errors, confidence intervals or scientific fits were recomputed.', '',
             'Skill = 1 - MSE(TCN with fast inputs) / MSE(reference); positive means lower TCN MSE.',
             'All values below are percentages of MSE reduction, including source 95% cluster intervals.',
             'TREE_TX is GP + boosted residual using fast/history/anchor summaries; TREE_T0 omits fast summaries.',
             'These are not the legacy LSTM + correction estimator. Different neural inner-VAL/fit budgets persist.',
             'FULL15 one-seed and FOUR units three-seed are separate, overlapping scopes, not independent replications.',
             'Source intervals are fixed-fit exploratory intervals without multiplicity/model-selection/refit uncertainty.',
             'D rules specify history source-age availability, not forecast horizon; F and L5 are different report targets.', '',
             'The cells below are a fixed overview matching the earlier four study statements, not new success criteria.', '']
    checks = []
    for scope, sr in z['scopes'].items():
        lines += ['## ' + scope, '',
                  '| Design | Cell | Reference | Skill % [95%] | Excludes zero | Paired rows | Excluded rows |',
                  '|---|---|---|---|---|---|---|']
        for design, dr in sr['designs'].items():
            for key in ('D10/F', 'D650/L5', 'S/L5', 'K10/L5'):
                for learner, p in dr['cells'][key]['supplementary_tree_pairs'].items():
                    lo, hi = p['cluster']
                    lines.append(f"| {design} | {key} | {learner} | {100*p['point']:+.2f} [{100*lo:+.2f}, {100*hi:+.2f}] | {p['excludes_zero']} | {p['rows']} | {p['excluded_from_cell']} |")
                    checks.append((scope, design, key, learner))
    lines += ['', '## Metadata-only reuse inventory', '',
              'Only idx/mask arrays were read for this inventory, never est/target values.',
              'B84 mixture GP+tree is L5-only, and has no V2 fits. Missing comparators stay missing.',
              'Index overlap does not establish manifest, target construction or information parity.', '',
              '| Reference | Existing metadata cells | Cells with full masked TCN index coverage |',
              '|---|---|---|']
    for label in ('specialized_GP_tree', 'mixture_GP_tree', 'D10_applied_GP_tree'):
        found = [c for c in inv['cells'] if c['reference'] == label and c['exists']]
        full = sum(c['tcn_index_rows_missing'] == 0 for c in found)
        lines.append(f'| {label} | {len(found)} | {full} |')
    lines += ['', 'Detailed indices/hash metadata stay in ignored `data/.tcn_merit_plan_20261124/index_inventory.json`.',
              '', '## Complete source matrix', '',
              'Every published cell is included below, including D10/F_full on its distinct support.', '',
              '| Scope | Design | Cell | Reference | Skill % [95%] | Excludes zero | Rows | Excluded |',
              '|---|---|---|---|---|---|---|---|']
    for scope, sr in z['scopes'].items():
        for design, dr in sr['designs'].items():
            for key, c in dr['cells'].items():
                for learner, p in c['supplementary_tree_pairs'].items():
                    lo, hi = p['cluster']
                    lines.append(f"| {scope} | {design} | {key} | {learner} | {100*p['point']:+.2f} [{100*lo:+.2f}, {100*hi:+.2f}] | {p['excludes_zero']} | {p['rows']} | {p['excluded_from_cell']} |")
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf8')
    print(json.dumps({'overview_rows': len(checks), 'source_cells': sum(len(d['cells']) for s in z['scopes'].values() for d in s['designs'].values()), 'report': str(OUT.relative_to(ROOT))}))


if __name__ == '__main__':
    main()
