# -*- coding: utf-8 -*-
"""Build docs/paper/ppcf/supp_data_fragment.tex from the data section of the supplement at commit ea2e1a6
(the manuscript on the earlier line): the paragraphs on the published geometry, the table of published
parameters, what a row holds and what the target is, with the cross-references to removed sections taken out.
    py make_supp_fragment.py <repo root>
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(sys.argv[1])
old = subprocess.run(["git", "show", "ea2e1a6:docs/paper/ppcf/supp_ppcf.tex"], cwd=ROOT, capture_output=True, check=True).stdout.decode("utf-8")
lines = old.splitlines()
a = next(i for i, ln in enumerate(lines) if ln.startswith("\\paragraph{Plasma and diagnostics.}"))
b = next(i for i, ln in enumerate(lines) if ln.startswith("\\section{The network: structure and design choices}"))
s = "\n".join(lines[a:b]).rstrip() + "\n"


def sub(old_, new_):
    global s
    if s.count(old_) != 1:
        raise SystemExit("FATAL: %d occurrences of: %s" % (s.count(old_), old_[:70]))
    s = s.replace(old_, new_)


def cut(start, end, keep_end=True):
    """Remove from the start marker (inclusive) to the end marker (exclusive if keep_end)."""
    global s
    if s.count(start) != 1 or s.count(end) != 1:
        raise SystemExit("FATAL: markers %d / %d: %s ... %s" % (s.count(start), s.count(end), start[:50], end[:50]))
    i, j = s.find(start), s.find(end)
    if j < i:
        raise SystemExit("FATAL: order of markers")
    s = s[:i] + (s[j:] if keep_end else s[j + len(end):])


sub("in the files the blips are 1.5\\,s apart in the two discharges of Fig.~\\ref{fig:bursts}, and 1{,}414 steps",
    "in the files 1{,}414 steps")
sub("(estimate from published formulas, \\S\\ref{sec:rows})", "(our estimate from published formulas)")
sub("the exposure setting of 2022; which beam source is switched off and when; the ECEI",
    "the exposure setting of 2022; the ECEI")
cut("; which step,", "): the fast channels are snapshots")
sub("The converse does not always hold\n(\\S\\ref{sec:bursts}: two interruptions of 23 and 26\\,ms that removed no frame).",
    "The converse does not always hold: in one discharge two interruptions of 23 and 26\\,ms\nremoved no frame.")
sub("The files therefore record the blips, though not the beam power.",
    "The beam files identify these interruptions as notches of the sources NB1B and NB1C\n(Table~\\ref{tab:nbinotch}).")
cut("From the series\nitself, the part of the reported value", "Published\nvalues for other analyses")
sub("(v) A bias\nthat changes when the analysis refreshes", "(v) A bias\nthat changes when the analysis refreshes")
sub("  \\footnotesize\n  \\begin{tabular}{p{0.24\\linewidth}p{0.48\\linewidth}p{0.20\\linewidth}}",
    "  \\scriptsize\n  \\begin{tabular}{p{0.19\\linewidth}p{0.55\\linewidth}p{0.17\\linewidth}}")
for bad in ("\\ref{sec:rows}", "\\ref{sec:bursts}", "\\ref{sec:yardsticks}", "\\ref{fig:bursts}", "\\ref{fig:missing}", "\\FloorRms", "\\ref{sec:vrot}"):
    if bad in s:
        raise SystemExit("FATAL: left-over reference " + bad)
head = "% generated by make_supp_fragment.py from the data section of the supplement at commit ea2e1a6; edit the script, not this file\n"
(ROOT / "docs" / "paper" / "ppcf" / "supp_data_fragment.tex").write_text(head + s, encoding="utf-8", newline="\n")
print("written, %d lines" % (s.count("\n")))
