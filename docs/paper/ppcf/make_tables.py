    three = all(x["three_initialisations"] for x in a)
    pooled = bool(P.get("complete"))
    L = ["% generated by make_tables.py from docs/paper/b39_primary.json -- do not edit",
         "\\newif\\ifpooled", "\\pooledtrue" if pooled else "\\pooledfalse",
         "\\newif\\ifthreeinit", "\\threeinittrue" if three else "\\threeinitfalse"]

