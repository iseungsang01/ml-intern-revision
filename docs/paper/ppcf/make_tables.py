"""Write the tables and the in-text numbers of main_ppcf.tex that come from B.39.

Reads docs/paper/b39_primary.json (written by ces_prediction/experiments/b39_primary/analyze_b39.py)
and writes docs/paper/ppcf/b39_generated.tex: \\ifpooled, the two tables (\\TabPrimary,
\\TabAblation) and the macros used in the prose.  Nothing is typed by hand; the numbers are
printed with the formats of b39_primary.md so that check_numbers.py finds them there.

Run from the repo root:  py docs/paper/ppcf/make_tables.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SRC = ROOT / "docs" / "paper" / "b39_primary.json"
OUT = HERE / "b39_generated.tex"
SEEDS = ("42", "1", "7", "123")
WORD = {0: "none", 1: "one", 2: "two", 3: "three", 4: "four"}


def cell(v):
    p = f"{v[0]:+.3f}"
    if v[1] > 0 or v[2] < 0:
        p = f"\\mathbf{{{p}}}"
    return f"${p}$ $[{v[1]:+.3f}, {v[2]:+.3f}]$"


def plain(v):
    return f"${v[0]:+.3f}$ $[{v[1]:+.3f}, {v[2]:+.3f}]$"


def rng(vals):
    lo, hi = min(v[0] for v in vals), max(v[0] for v in vals)
    return f"${lo:+.3f}$ to ${hi:+.3f}$"


def above(vals):
    return WORD[sum(v[1] > 0 for v in vals)] + " of four"


def excl(vals):
    return WORD[sum(v[1] > 0 or v[2] < 0 for v in vals)] + " of four"


def listing(xs, fmt="{:.1f}"):
    s = [fmt.format(x) for x in xs]
    return ", ".join(s[:-1]) + " and " + s[-1]


def main():
    res = json.loads(SRC.read_text(encoding="utf-8"))
    A, P = res["A"], res["P"]
    assert all(s in A for s in SEEDS), "arm A is not complete on four splits"
    a = [A[s] for s in SEEDS]
    three = all(x["three_initialisations"] for x in a)
    pooled = bool(P.get("complete"))
    L = ["% generated by make_tables.py from docs/paper/b39_primary.json -- do not edit",
         "\\newif\\ifpooled", "\\pooledtrue" if pooled else "\\pooledfalse",
         "\\newif\\ifthreeinit", "\\threeinittrue" if three else "\\threeinitfalse"]

    def mac(name, body):
        L.append(f"\\newcommand{{\\{name}}}{{{body}}}")

    S1 = [x["S1_causal_over_gp"] for x in a]
    S2 = [x["S2_causal_over_twin"] for x in a]
    TW = [x["twin_over_gp"] for x in a]
    HO = [x["causal_over"]["persistence"] for x in a]
    PC = [x["causal_over"]["pchip"] for x in a]
    OG = [x["causal_over"]["gp"] for x in a]
    D1 = [x["D1_ecei_over_twin"] for x in a]
    D2 = [x["D2_bes_over_twin"] for x in a]
    NM = [x["nomirnov_over_twin"] for x in a]
    FT = [x["full_over_twin_same_initialisation"] for x in a]
    FE = [x["full_over_ecei"] for x in a]
    FB = [x["full_over_bes"] for x in a]
    FN = [x["full_over_nomirnov"] for x in a]
    for name, v in (("Sone", S1), ("Stwo", S2), ("TwinGp", TW), ("OverHold", HO), ("OverPchip", PC),
                    ("OverOffGp", OG), ("Done", D1), ("Dtwo", D2), ("NoMirTwin", NM), ("FullTwin", FT),
                    ("FullEcei", FE), ("FullBes", FB), ("FullNoMir", FN)):
        mac(name + "Range", rng(v))
        mac(name + "Above", above(v))
        mac(name + "Excl", excl(v))
    med = lambda k: [x["median_abs_error_eV"][k] for x in a]      # noqa: E731
    rms = lambda k: [x["rmse_eV"][k] for x in a]                  # noqa: E731
    mac("MedHold", listing(med("hold")))
    mac("MedGp", listing(med("causal GP")))
    mac("MedTwin", listing(med("twin")))
    mac("MedCausal", listing(med("causal variant")))
    mac("SpreadRange", "{:.3f} to {:.3f}".format(min(x["spread_causal_over_gp"] for x in a),
                                                 max(x["spread_causal_over_gp"] for x in a)))
    mac("RowsFirst", f"{a[0]['rows']:,}".replace(",", "{,}"))
    mac("ShotsFirst", str(a[0]["discharges"]))
    if pooled:
        mac("Pone", plain(P["P1_causal_over_gp"]))
        mac("Ptwo", plain(P["P2_causal_over_twin"]))
        mac("PoneFold", "$[{:+.3f}, {:+.3f}]$".format(*P["P1_fold_level_nadeau_bengio"][1:]))
        mac("PtwoFold", "$[{:+.3f}, {:+.3f}]$".format(*P["P2_fold_level_nadeau_bengio"][1:]))
        mac("PHold", plain(P["causal_over"]["persistence"]))
        mac("PPchip", plain(P["causal_over"]["pchip"]))
        mac("POffGp", plain(P["causal_over"]["gp"]))
        mac("PTwinGp", plain(P["twin_over_gp"]))
        pm = P["median_abs_error_eV"]
        mac("PMed", "{:.1f}, {:.1f} and {:.1f}".format(pm["hold"], pm["twin"], pm["causal variant"]))

    cols = "l" + "c" * (5 if pooled else 4)
    head = ("Pooled & " if pooled else "") + "Split 1 & Split 2 & Split 3 & Split 4"

    def row(label, vals, pv=None, f=cell):
        cells = ([f(pv)] if pooled and pv is not None else (["--"] if pooled else [])) + [f(v) for v in vals]
        return f"    {label} & " + " & ".join(cells) + " \\\\"

    def nrow(label, vals, fmt, pv=None):
        cells = ([fmt.format(pv)] if pooled and pv is not None else (["--"] if pooled else [])) \
            + [fmt.format(v) for v in vals]
        return f"    {label} & " + " & ".join(cells) + " \\\\"

    Pc = P.get("causal_over", {}) if pooled else {}
    T = ["\\newcommand{\\TabPrimary}{%", "  \\resizebox{\\linewidth}{!}{%", f"  \\begin{{tabular}}{{{cols}}}",
         "    \\toprule", f"    & {head} \\\\", "    \\midrule",
         "    \\multicolumn{%d}{l}{\\emph{Skill of the recurrent estimator over}} \\\\" % (len(cols)),
         row("\\quad hold", HO, Pc.get("persistence")),
         row("\\quad causal GP", S1, P.get("P1_causal_over_gp")),
         row("\\quad history-only twin", S2, P.get("P2_causal_over_twin")),
         row("\\quad PCHIP (uses the next sample)", PC, Pc.get("pchip")),
         row("\\quad offline GP (uses the next sample)", OG, Pc.get("gp")),
         "    \\midrule",
         row("History-only twin over causal GP", TW, P.get("twin_over_gp")),
         "    \\midrule",
         "    \\multicolumn{%d}{l}{\\emph{Median absolute error (eV)}} \\\\" % (len(cols)),
         nrow("\\quad hold", med("hold"), "{:.1f}", P.get("median_abs_error_eV", {}).get("hold")),
         nrow("\\quad causal GP", med("causal GP"), "{:.1f}"),
         nrow("\\quad history-only twin", med("twin"), "{:.1f}", P.get("median_abs_error_eV", {}).get("twin")),
         nrow("\\quad recurrent estimator", med("causal variant"), "{:.1f}",
              P.get("median_abs_error_eV", {}).get("causal variant")),
         "    \\multicolumn{%d}{l}{\\emph{Root-mean-square error (eV)}} \\\\" % (len(cols)),
         nrow("\\quad hold", rms("hold"), "{:.1f}"),
         nrow("\\quad causal GP", rms("causal GP"), "{:.1f}"),
         nrow("\\quad history-only twin", rms("twin"), "{:.1f}"),
         nrow("\\quad recurrent estimator", rms("causal variant"), "{:.1f}"),
         "    \\midrule",
         "    Scored rows / test discharges & " + ("-- & " if pooled else "")
         + " & ".join(f"{x['rows']:,}".replace(",", "{,}") + f" / {x['discharges']}" for x in a) + " \\\\",
         "    \\bottomrule", "  \\end{tabular}}}"]
    L += T
    T = ["\\newcommand{\\TabAblation}{%", "  \\resizebox{\\linewidth}{!}{%", "  \\begin{tabular}{lcccc}",
         "    \\toprule", "    & Split 1 & Split 2 & Split 3 & Split 4 \\\\", "    \\midrule",
         "    \\multicolumn{5}{l}{\\emph{Over the history-only twin}} \\\\",
         "    \\quad BES and CES history & " + " & ".join(cell(v) for v in D2) + " \\\\",
         "    \\quad ECEI and CES history & " + " & ".join(cell(v) for v in D1) + " \\\\",
         "    \\quad BES, ECEI and CES history (no Mirnov) & " + " & ".join(cell(v) for v in NM) + " \\\\",
         "    \\quad all fast channels and CES history & " + " & ".join(cell(v) for v in FT) + " \\\\",
         "    \\midrule",
         "    \\multicolumn{5}{l}{\\emph{All fast channels over}} \\\\",
         "    \\quad BES and CES history & " + " & ".join(cell(v) for v in FB) + " \\\\",
         "    \\quad ECEI and CES history & " + " & ".join(cell(v) for v in FE) + " \\\\",
         "    \\quad BES, ECEI and CES history (no Mirnov) & " + " & ".join(cell(v) for v in FN) + " \\\\",
         "    \\bottomrule", "  \\end{tabular}}}"]
    L += T
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("written", OUT.name, "| three initialisations:", three, "| pooled:", pooled)


if __name__ == "__main__":
    main()
